export const API_MESSAGES = Object.freeze(Object.fromEntries(API_LOCALES.map((locale, index) => [locale,
  Object.freeze(Object.fromEntries(Object.entries(messages).map(([key, values]) => [key, values[index]]))),
])));

export function apiText(key, values = {}, locale = getSiteLocale()) {
  const message = API_MESSAGES[locale]?.[key];
  if (typeof message !== 'string') throw new Error(`Missing API translation: ${locale}.${key}`);
  return message.replace(/\{(\w+)\}/g, (token, name) => Object.hasOwn(values, name) ? String(values[name]) : token);
}

/** Only declared leaf labels and attributes are translated. Inputs, code and runtime data are untouched. */
export function applyApiLocale(root, locale = getSiteLocale()) {
  for (const element of root.querySelectorAll('[data-api-i18n]')) {
    const value = apiText(element.dataset.apiI18n, {}, locale);
    if (element.textContent !== value) element.textContent = value;
  }
  for (const element of root.querySelectorAll('[data-api-i18n-aria-label]')) {
    element.setAttribute('aria-label', apiText(element.dataset.apiI18nAriaLabel, {}, locale));
  }
}

/** Errors carry stable keys, so an existing validation message can change language safely. */
export function apiError(key, values = {}, ErrorType = TypeError) {
  const error = new ErrorType(apiText(key, values));
  error.apiMessage = { key, values };
  return error;
}
